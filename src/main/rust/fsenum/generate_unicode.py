"""Write src/unicode.rs: the Unicode tables natural keys need, from this Python.

    python src/main/rust/fsenum/generate_unicode.py [--check]

Natural keys must equal fman.impl.util.natural.natural_key for every name, so
the tables come from the interpreter the application ships with, not from
Rust's own Unicode data:

* lower-case mappings: chr(c).lower() for every code point;
* the Final_Sigma context of str.lower(): its case-ignorable and cased sets,
  derived by probing str.lower() around U+03A3;
* decimal digits (re's \\d): str.isdecimal() and unicodedata.decimal().

--check exits 1 when src/unicode.rs differs from what this Python generates.
Rebuild _fsenum.pyd after regenerating (README.md).
"""

import argparse
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUTPUT = HERE / 'src' / 'unicode.rs'
CAPITAL_SIGMA, SMALL_SIGMA, FINAL_SIGMA = '\u03a3', '\u03c3', '\u03c2'


def ranges(codes):
	result = []
	for code in codes:
		if result and result[-1][1] == code - 1:
			result[-1][1] = code
		else:
			result.append([code, code])
	return result


def tables():
	lower, ignorable, cased, digits = [], [], [], []
	for code in range(0x110000):
		character = chr(code)
		mapped = character.lower()
		if mapped != character:
			lower.append((code, tuple(map(ord, mapped))))
		# str.lower() maps U+03A3 to final sigma when a cased letter precedes it
		# (skipping case-ignorable ones) and none follows. Probing both sides
		# separates the two sets as str.lower() applies them.
		before = ('A' + character + CAPITAL_SIGMA).lower()[-1]
		alone = (character + CAPITAL_SIGMA).lower()[-1]
		if before == FINAL_SIGMA and alone == SMALL_SIGMA:
			ignorable.append(code)
		elif alone == FINAL_SIGMA:
			cased.append(code)
		if character.isdecimal():
			digits.append((code, unicodedata.decimal(character)))
	if max(len(mapping) for _, mapping in lower) > 3:
		raise SystemExit('A lower-case mapping is longer than three code points')
	latin1 = []
	for code in range(256):
		mapped = chr(code).lower()
		if len(mapped) != 1 or ord(mapped) > 255:
			raise SystemExit('Latin-1 lower-case mapping leaves Latin-1: U+%04X' % code)
		latin1.append(ord(mapped))
	decimal = []
	for code, value in digits:
		if decimal and decimal[-1][1] == code - 1 and decimal[-1][2] + (code - decimal[-1][0]) == value:
			decimal[-1][1] = code
		else:
			decimal.append([code, code, value])
	return latin1, lower, ranges(ignorable), ranges(cased), decimal


def render():
	latin1, lower, ignorable, cased, decimal = tables()
	lines = [
		'// Generated by generate_unicode.py from Python %s (Unicode %s). Do not edit.' % (
			sys.version.split()[0], unicodedata.unidata_version),
		'',
		'pub const UNICODE_VERSION: &str = "%s";' % unicodedata.unidata_version,
		'',
		'/// chr(c).lower() for c < 256; always a single Latin-1 character.',
		'pub static LATIN1_LOWER: [u8; 256] = [',
	]
	for start in range(0, 256, 16):
		lines.append('    ' + ', '.join('0x%02X' % value for value in latin1[start:start + 16]) + ',')
	lines += ['];', '',
		'/// (code point, chr(c).lower() padded with zeros) where the mapping differs.',
		'pub static LOWER: [(u32, [u32; 3]); %d] = [' % len(lower)]
	for code, mapping in lower:
		padded = mapping + (0,) * (3 - len(mapping))
		lines.append('    (0x%04X, [%s]),' % (code, ', '.join('0x%04X' % value for value in padded)))
	lines += ['];', '']
	for name, values, comment in (
			('CASE_IGNORABLE', ignorable, 'Skipped around U+03A3 by str.lower() (inclusive ranges).'),
			('CASED', cased, 'Cased and not case-ignorable, as str.lower() tests them (inclusive ranges).')):
		lines += ['/// %s' % comment, 'pub static %s: [(u32, u32); %d] = [' % (name, len(values))]
		lines += ['    (0x%04X, 0x%04X),' % (first, last) for first, last in values]
		lines += ['];', '']
	lines += ['/// Decimal digits (re \\d): (first, last, value of first); values rise by one.',
		'pub static DECIMAL: [(u32, u32, u8); %d] = [' % len(decimal)]
	lines += ['    (0x%04X, 0x%04X, %d),' % tuple(entry) for entry in decimal]
	lines += ['];', '']
	return '\n'.join(lines)


def main(argv=None):
	parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
	parser.add_argument('--check', action='store_true', help='compare instead of writing')
	args = parser.parse_args(argv)
	text = render()
	if args.check:
		current = OUTPUT.read_text(encoding='utf-8').replace('\r\n', '\n') if OUTPUT.is_file() else ''
		if current != text:
			print('%s differs from this Python (Unicode %s); regenerate and rebuild' % (OUTPUT, unicodedata.unidata_version))
			return 1
		print('%s matches Unicode %s' % (OUTPUT.name, unicodedata.unidata_version))
		return 0
	OUTPUT.parent.mkdir(parents=True, exist_ok=True)
	OUTPUT.write_text(text, encoding='utf-8', newline='\n')
	print('Wrote %s (Unicode %s)' % (OUTPUT, unicodedata.unidata_version))
	return 0


if __name__ == '__main__':
	sys.exit(main())
